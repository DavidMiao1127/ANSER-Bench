#!/usr/bin/env python3
"""Build exact FAISS dense indexes from ANSER-Bench BM25 document stores.

The input stores are generated by ``run_benchmark.py --method sparse
--build-index-only``. This script embeds their already-normalized documents,
so sparse and dense RAG share corpus routing, chunking, and evidence mapping.
"""

from __future__ import annotations

import argparse
import json
import sqlite3
import sys
from pathlib import Path
from typing import Any, Iterator


PROJECT_ROOT = Path(__file__).resolve().parents[2]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))


def dependencies() -> tuple[Any, Any, Any]:
    try:
        import faiss
        import numpy as np
    except ImportError as exc:
        raise RuntimeError(
            "Dense index construction requires faiss-cpu and numpy; local embeddings additionally need torch and sentence-transformers. "
            "Install requirements-dense.txt before running this command."
        ) from exc
    return faiss, np


def documents(path: Path, batch_size: int) -> Iterator[tuple[list[int], list[str]]]:
    with sqlite3.connect(path.resolve().as_uri() + "?mode=ro", uri=True) as conn:
        cursor = conn.execute("SELECT rowid, text FROM documents ORDER BY rowid")
        while rows := cursor.fetchmany(batch_size):
            yield [int(row[0]) for row in rows], [str(row[1]) for row in rows]


def build_one(args: argparse.Namespace, route: str) -> None:
    faiss, np = dependencies()
    from src.common.embedding import create_client, signature
    source = args.bm25_index_dir / f"{route}.sqlite"
    target = args.index_dir / f"{route}.faiss"
    metadata_path = args.index_dir / f"{route}.json"
    if not source.is_file():
        raise FileNotFoundError(f"Missing completed BM25 document store: {source}")
    if (target.exists() or metadata_path.exists()) and not args.overwrite:
        raise FileExistsError(f"Dense index already exists for {route}; use --overwrite to replace it.")

    encoder = create_client(args,build=True)
    # DenseIndex.search uses returned FAISS labels as SQLite rowids. An ID map
    # preserves that relationship even if a document store has rowid gaps.
    index = faiss.IndexIDMap2(faiss.IndexFlatIP(args.embedding_dim))
    for ids, texts in documents(source, args.batch_size):
        matrix = encoder.embed([args.embedding_document_prefix+text for text in texts])
        if matrix.shape != (len(texts), args.embedding_dim):
            raise RuntimeError(f"Unexpected embedding shape {matrix.shape} for {route}")
        faiss.normalize_L2(matrix)
        index.add_with_ids(matrix, np.asarray(ids, dtype="int64"))
        print(f"[{route}] indexed {index.ntotal:,} documents", file=sys.stderr, flush=True)

    args.index_dir.mkdir(parents=True, exist_ok=True)
    temporary_index = target.with_suffix(".faiss.tmp")
    temporary_meta = metadata_path.with_suffix(".json.tmp")
    faiss.write_index(index, str(temporary_index))
    temporary_meta.write_text(
        json.dumps(
            {
                **signature(args),
                "route": route,
                "embedding_model": args.embedding_model,
                "dimension": args.embedding_dim,
                "index_type": "FlatIP-inner-product-normalized",
                "documents": index.ntotal,
                "state": "complete",
            },
            ensure_ascii=False,
            indent=2,
        ) + "\n",
        encoding="utf-8",
    )
    temporary_index.replace(target)
    temporary_meta.replace(metadata_path)
    print(f"[{route}] wrote {target} ({index.ntotal:,} vectors)")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bm25-index-dir", type=Path, default=PROJECT_ROOT / "indices" / "bm25")
    parser.add_argument("--index-dir", type=Path, default=PROJECT_ROOT / "indices" / "dense")
    parser.add_argument("--routes", nargs="*", help="BM25 route names; defaults to every *.sqlite index.")
    from src.common.embedding import add_arguments
    add_arguments(parser)
    parser.add_argument("--max-length", type=int, default=1024)
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--device", default="cuda:0")
    parser.add_argument("--local-files-only", action="store_true")
    parser.add_argument("--attn-implementation", choices=("auto", "sdpa", "eager", "flash_attention_2"), default="auto")
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()
    if min(args.embedding_dim, args.max_length, args.batch_size) < 1:
        raise ValueError("embedding dimension, max length, and batch size must be positive")
    args.bm25_index_dir = args.bm25_index_dir.resolve()
    args.index_dir = args.index_dir.resolve()
    routes = args.routes or sorted(path.stem for path in args.bm25_index_dir.glob("*.sqlite"))
    if not routes:
        raise FileNotFoundError(f"No BM25 document stores found in {args.bm25_index_dir}")
    for route in routes:
        build_one(args, route)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
